"""Vtable layouts of the DirectDraw / Direct3D 7 interfaces, read from the Windows SDK headers.

Usage:
    dx_methods.py                      print every interface with its methods and vtable offsets
    dx_methods.py --cpp <out.inc>      write the C++ method-name tables used by src/diagnostics/DirectXTrace.cpp

The SDK declares each interface with DECLARE_INTERFACE_(Name, Base) and STDMETHOD/STDMETHOD_ lines in vtable order,
the three IUnknown methods first.
"""

from __future__ import annotations

import glob
import os
import re
import sys

INTERFACES = [
    # (header, interface) in the order the C++ table uses
    ("ddraw.h", "IDirectDraw"),
    ("ddraw.h", "IDirectDraw2"),
    ("ddraw.h", "IDirectDraw4"),
    ("ddraw.h", "IDirectDraw7"),
    ("ddraw.h", "IDirectDrawSurface"),
    ("ddraw.h", "IDirectDrawSurface2"),
    ("ddraw.h", "IDirectDrawSurface3"),
    ("ddraw.h", "IDirectDrawSurface4"),
    ("ddraw.h", "IDirectDrawSurface7"),
    ("ddraw.h", "IDirectDrawClipper"),
    ("ddraw.h", "IDirectDrawPalette"),
    ("ddraw.h", "IDirectDrawGammaControl"),
    ("d3d.h", "IDirect3D7"),
    ("d3d.h", "IDirect3DDevice7"),
    ("d3d.h", "IDirect3DVertexBuffer7"),
]


def sdk_header(name: str) -> str:
    candidates = sorted(glob.glob(rf"C:\Program Files (x86)\Windows Kits\10\Include\*\um\{name}"))
    if not candidates:
        raise SystemExit(f"{name} not found in the Windows 10 SDK")
    return candidates[-1]


def methods(header_text: str, interface: str) -> list[str]:
    start = re.search(rf"DECLARE_INTERFACE_\(\s*{interface}\s*,", header_text)
    if not start:
        raise SystemExit(f"{interface} not declared")
    body = header_text[start.end():header_text.index("};", start.end())]
    return re.findall(r"STDMETHOD_?\s*\(\s*(?:[^,()]+,\s*)?(\w+)\s*\)", body)


def load() -> list[tuple[str, list[str]]]:
    texts: dict[str, str] = {}
    result = []
    for header, interface in INTERFACES:
        if header not in texts:
            texts[header] = open(sdk_header(header), encoding="latin-1").read()
        result.append((interface, methods(texts[header], interface)))
    return result


def write_cpp(path: str) -> None:
    lines = ["// Generated by tools/dx_methods.py from the Windows SDK headers; do not edit.", ""]
    for interface, names in load():
        quoted = ", ".join(f'"{n}"' for n in names)
        lines.append(f"inline constexpr const char* k{interface}Methods[] = {{{quoted}}};")
    lines.append("")
    open(path, "w", encoding="utf-8", newline="\n").write("\n".join(lines))


def main() -> None:
    if len(sys.argv) == 3 and sys.argv[1] == "--cpp":
        write_cpp(sys.argv[2])
        return
    for interface, names in load():
        print(f"{interface} ({len(names)} methods)")
        for index, name in enumerate(names):
            print(f"  0x{index * 4:03x} {name}")


if __name__ == "__main__":
    main()
